// The roles that may call each operation, from `x-roles` in the OpenAPI contract (ADR 0027, `@AllowedRoles` on the
// handler). Generated with the API types by `npm run gen:api`; the output is not committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const spec = JSON.parse(readFileSync(join(root, '../api/openapi/etrm-api.json'), 'utf8'));

const entries = Object.values(spec.paths)
  .flatMap((methods) => Object.values(methods))
  .filter((op) => op && typeof op === 'object' && op.operationId && Array.isArray(op['x-roles']))
  .map((op) => [op.operationId, op['x-roles']])
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([id, roles]) => `  ${id}: [${roles.map((r) => `'${r}'`).join(', ')}],`).join('\n');
const out = `// Generated by scripts/gen-permissions.mjs from x-roles in the OpenAPI contract. Do not edit.
import type { OperationId, Role } from '@/shared/api/types';

export const GENERATED_PERMISSIONS: Partial<Record<OperationId, readonly Role[]>> = {
${body}
};
`;
writeFileSync(join(root, 'src/shared/auth/permissions.generated.ts'), out);
console.log(`permissions: ${entries.length} operations with roles`);
